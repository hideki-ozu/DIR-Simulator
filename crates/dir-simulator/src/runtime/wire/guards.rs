const APPLICANTS: &[&str] = &[
    "VO", "VP", "VN", "AN", "AA", "QA", "LA", "AO", "QO", "AP", "QP", "LO",
];
const REGISTRARS: &[&str] = &["IN", "LV", "MT"];
const APPLICANT_CONTROLS: &[&str] = &["normal", "new_only", "non_participant"];
const REGISTRAR_CONTROLS: &[&str] = &[
    "normal",
    "fixed_ignore_new",
    "fixed_propagate_new",
    "forbidden",
];
const AUXILIARY_STATES: &[&str] = &["Active", "Passive"];
const LEAVEALL_EVENTS: &[&str] = &["Begin", "ReceiveLeaveAll", "LeaveAllExpired", "Tx"];
const PERIODIC_EVENTS: &[&str] = &["Begin", "PeriodicExpired", "Enabled", "Disabled"];
const MRP_TABLES: &[(&str, &str, usize, usize)] = &[
    ("Applicant", "DIR-MRP-Applicant-cells-v1", 7776, 648),
    ("Registrar", "DIR-MRP-Registrar-cells-v1", 432, 144),
    ("LeaveAll", "DIR-MRP-LeaveAll-cells-v1", 8, 4),
    ("Periodic", "DIR-MRP-Periodic-cells-v1", 8, 4),
];
fn index(values: &[&str], value: &str) -> usize {
    values
        .iter()
        .position(|v| *v == value)
        .unwrap_or_else(|| panic!("unknown guard discriminator {value}"))
}
fn field<'a>(value: &'a serde_json::Value, key: &str) -> &'a str {
    value[key]
        .as_str()
        .unwrap_or_else(|| panic!("missing string guard discriminator {key}"))
}
// Frozen full-cell enumeration, NOT IEEE table row numbers. Inputs only;
// lookup neither computes a transition nor inspects expected output/state.
#[allow(clippy::too_many_arguments)]
fn mrp_cell(
    machine: &str,
    event: &str,
    before: &serde_json::Value,
    after: &serde_json::Value,
    applicant_control: &str,
    registrar_control: &str,
    p2p: bool,
    room: bool,
) -> usize {
    match machine {
        "Applicant" => {
            let source = index(APPLICANTS, field(before, "applicant"));
            let event = index(EVENTS, event);
            let control = index(APPLICANT_CONTROLS, applicant_control);
            let registrar = index(REGISTRARS, field(after, "registrar"));
            (((((source * 18 + event) * 3 + control) * 3 + registrar) * 2 + usize::from(p2p)) * 2
                + usize::from(room))
                + 1
        }
        "Registrar" => {
            let source = index(REGISTRARS, field(before, "registrar"));
            let event = index(EVENTS, event);
            let control = index(REGISTRAR_CONTROLS, registrar_control);
            (((source * 18 + event) * 4 + control) * 2 + usize::from(p2p)) + 1
        }
        "LeaveAll" | "Periodic" => {
            let source = index(AUXILIARY_STATES, field(before, "state"));
            source * 4
                + index(
                    if machine == "LeaveAll" {
                        LEAVEALL_EVENTS
                    } else {
                        PERIODIC_EVENTS
                    },
                    event,
                )
                + 1
        }
        _ => panic!("unknown MRP machine {machine}"),
    }
}
#[allow(clippy::too_many_arguments)]
pub(crate) fn mvrp(
    machine: &str,
    event: &str,
    before: &serde_json::Value,
    after: &serde_json::Value,
    applicant_control: &str,
    registrar_control: &str,
    p2p: bool,
    room: bool,
) -> String {
    let cell = mrp_cell(
        machine,
        event,
        before,
        after,
        applicant_control,
        registrar_control,
        p2p,
        room,
    );
    mrp_catalog().cells[machine][cell - 1].clone()
}
struct MrpCatalog {
    cells: std::collections::BTreeMap<&'static str, Vec<String>>,
    ids: std::collections::BTreeMap<&'static str, std::collections::BTreeSet<String>>,
}
fn mrp_catalog() -> &'static MrpCatalog {
    static CATALOG: std::sync::LazyLock<MrpCatalog> = std::sync::LazyLock::new(|| {
        let mut cells = std::collections::BTreeMap::new();
        let mut ids = std::collections::BTreeMap::new();
        for &(machine, section, size, source_stride) in MRP_TABLES {
            let fixtures = match machine {
                "Applicant" => APPLICANT_FIXTURES,
                "Registrar" => REGISTRAR_FIXTURES,
                "LeaveAll" => LEAVEALL_FIXTURES,
                "Periodic" => PERIODIC_FIXTURES,
                _ => unreachable!(),
            };
            let event_stride = source_stride / if size > 8 { 18 } else { 4 };
            let mut rows: Vec<_> = (1..=size)
                .map(|cell| {
                    if (cell - 1) % source_stride < event_stride {
                        "BEGIN".into()
                    } else {
                        format!("{machine}/rule/{section}/{cell}")
                    }
                })
                .collect();
            for &(cell, fixture) in fixtures {
                rows[cell - 1] = format!("P-MVRP-T01-V{fixture}");
            }
            ids.insert(machine, rows.iter().cloned().collect());
            cells.insert(machine, rows);
        }
        MrpCatalog { cells, ids }
    });
    &CATALOG
}

